/* ============================================================
   i18n runtime
   ============================================================ */
window.epsos = window.epsos || {};

epsos.getLang = function () {
  return localStorage.getItem("epsos_lang") || "he";
};

epsos.setLang = function (lang) {
  localStorage.setItem("epsos_lang", lang);
  epsos.applyLang();
};

epsos.t = function (key) {
  const lang = epsos.getLang();
  return (window.I18N[lang] && window.I18N[lang][key]) || key;
};

epsos.applyLang = function () {
  const lang = epsos.getLang();
  const dict = window.I18N[lang];
  if (!dict) return;

  document.documentElement.lang = lang;
  document.documentElement.dir = dict.dir;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const key = el.getAttribute("data-i18n-ph");
    if (dict[key] !== undefined) el.setAttribute("placeholder", dict[key]);
  });

  document.querySelectorAll(".lang-switch button").forEach(b => {
    b.classList.toggle("active", b.dataset.lang === lang);
  });

  // Re-render any dynamic question content
  if (typeof window.renderCurrent === "function") window.renderCurrent();
};

epsos.bindLangSwitch = function (root) {
  (root || document).querySelectorAll(".lang-switch button").forEach(b => {
    b.addEventListener("click", () => epsos.setLang(b.dataset.lang));
  });
};
